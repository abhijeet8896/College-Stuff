# 9. SURF and HOG Feature Descriptor

import cv2
import numpy as np
import matplotlib.pyplot as plt

print(cv2.__file__)
print(hasattr(cv2, "HOGDescriptor"))


image = np.zeros((128, 64), dtype=np.uint8)
cv2.rectangle(image, (12, 15), (50, 112), 220, -1)
cv2.line(image, (12, 15), (50, 112), 255, 3)

# HOG descriptor
hog = cv2.HOGDescriptor(
    _winSize=(64, 128),
    _blockSize=(16, 16),
    _blockStride=(8, 8),
    _cellSize=(8, 8),
    _nbins=9
)
hog_features = hog.compute(image)

print("HOG descriptor length:", len(hog_features))
print("HOG descriptor shape:", hog_features.shape)

# SURF is often unavailable in standard Colab OpenCV builds because it
# belongs to the non-free/contrib feature set. Check availability safely.
if hasattr(cv2, "xfeatures2d") and hasattr(cv2.xfeatures2d, "SURF_create"):
    try:
        surf = cv2.xfeatures2d.SURF_create()
        keypoints, surf_descriptors = surf.detectAndCompute(image, None)
        print("SURF keypoints:", len(keypoints))
        print("SURF descriptor shape:",
              None if surf_descriptors is None else surf_descriptors.shape)
    except cv2.error:
        print("SURF is present but disabled in this OpenCV build.")
else:
    print("SURF is unavailable in this OpenCV build; HOG ran successfully.")

plt.figure(figsize=(3, 5))
plt.imshow(image, cmap="gray")
plt.title("Image used for HOG / SURF")
plt.axis("off")
plt.show()

