# 3. Compute Homography Matrix

import cv2
import numpy as np

# Four corresponding points in two image planes
src = np.float32([[0, 0], [200, 0], [200, 150], [0, 150]])
dst = np.float32([[20, 15], [220, 5], [210, 170], [10, 160]])

H, mask = cv2.findHomography(src, dst, method=0)

print("Homography matrix:")
print(np.round(H, 4))

# Transform the source points and compare with destination points
src_h = np.concatenate([src, np.ones((len(src), 1))], axis=1)
projected_h = (H @ src_h.T).T
projected = projected_h[:, :2] / projected_h[:, 2:3]

print("\nProjected points:")
print(np.round(projected, 2))
print("\nMaximum point error:", round(float(np.max(np.linalg.norm(projected - dst, axis=1))), 4))

