# 5. Camera Calibration

import cv2
import numpy as np

# Demonstration with synthetic chessboard-corner observations.
# Real calibration should use corners detected in multiple chessboard photos.
pattern_size = (7, 6)
square_size = 1.0

objp = np.zeros((pattern_size[0] * pattern_size[1], 3), np.float32)
objp[:, :2] = np.mgrid[0:pattern_size[0], 0:pattern_size[1]].T.reshape(-1, 2)
objp *= square_size

image_size = (640, 480)
objpoints = []
imgpoints = []

# Create several plausible 2D corner sets from the planar grid
for i in range(8):
    pts = objp[:, :2].copy()
    pts[:, 0] = 500 + (pts[:, 0] - 3) * (35 + i)
    pts[:, 1] = 350 + (pts[:, 1] - 2.5) * (34 + i * 0.7)
    pts += np.random.default_rng(i).normal(0, 0.15, pts.shape).astype(np.float32)
    imgpoints.append(pts.reshape(-1, 1, 2))
    objpoints.append(objp.copy())

# Synthetic observations are for demonstrating the API, not precision calibration.
rms, camera_matrix, dist_coeffs, rvecs, tvecs = cv2.calibrateCamera(
    objpoints, imgpoints, image_size, None, None
)

print("Calibration RMS error:", round(rms, 4))
print("Camera matrix shape:", camera_matrix.shape)
print("Distortion coefficients shape:", dist_coeffs.shape)
print("Number of calibration views:", len(objpoints))
print("\nCamera matrix:\n", np.round(camera_matrix, 3))

# 6. Compute Fundamental Matrix

import cv2
import numpy as np

rng = np.random.default_rng(7)
n = 30

# Generate matching points with a simple stereo-like horizontal displacement.
pts1 = rng.uniform(50, 400, (n, 2)).astype(np.float32)
disparity = rng.uniform(5, 30, (n, 1)).astype(np.float32)
pts2 = pts1.copy()
pts2[:, 0:1] -= disparity
pts1_cv = pts1.reshape(-1, 1, 2)
pts2_cv = pts2.reshape(-1, 1, 2)

F, inliers = cv2.findFundamentalMat(pts1_cv, pts2_cv, cv2.FM_RANSAC, 1.0, 0.99)

print("Fundamental matrix:")
print(F)
print("Matrix shape:", None if F is None else F.shape)
print("Number of inliers:", 0 if inliers is None else int(inliers.sum()))
print("Number of correspondences:", n)

# Epipolar constraint: x2^T F x1 should be near zero for inlier matches.
if F is not None and F.shape == (3, 3):
    x1 = np.hstack([pts1, np.ones((n, 1))])
    x2 = np.hstack([pts2, np.ones((n, 1))])
    errors = np.abs(np.sum(x2 * (F @ x1.T).T, axis=1))
    print("Mean epipolar constraint error:", float(np.mean(errors)))

# 7. Edge Detection, Line Detection and Corner Detection

import cv2
import matplotlib.pyplot as plt
import numpy as np

# 1. Create a blank grayscale image and draw shapes
image = np.zeros((260, 320), dtype=np.uint8)
cv2.rectangle(image, (35, 35), (135, 180), 220, -1)
cv2.line(image, (170, 220), (290, 45), 255, 4)
cv2.circle(image, (220, 145), 35, 180, -1)

# 2. Edge detection & Hough Line Transform
edges = cv2.Canny(image, 60, 150)
lines = cv2.HoughLinesP(
    edges, 1, np.pi / 180, threshold=25, minLineLength=25, maxLineGap=8
)

color = cv2.cvtColor(image, cv2.COLOR_GRAY2BGR)
line_count = 0

if lines is not None:
  line_count = len(lines)
  for line in lines:
    x1, y1, x2, y2 = line.ravel()  # Safely unpacks (1, 4) or (4,) shapes
    cv2.line(color, (int(x1), int(y1)), (int(x2), int(y2)), (0, 0, 255), 2)

# 3. Shi-Tomasi Corner Detection
corners = cv2.goodFeaturesToTrack(
    image, maxCorners=50, qualityLevel=0.01, minDistance=10
)
corner_count = 0 if corners is None else len(corners)

if corners is not None:
  for c in np.intp(corners):
    x, y = c.ravel()
    cv2.circle(color, (int(x), int(y)), 4, (0, 255, 0), -1)

# 4. Visualization
fig, ax = plt.subplots(1, 3, figsize=(11, 3.5))
ax[0].imshow(image, cmap="gray")
ax[0].set_title("Original")

ax[1].imshow(edges, cmap="gray")
ax[1].set_title("Canny edges")

ax[2].imshow(cv2.cvtColor(color, cv2.COLOR_BGR2RGB))
ax[2].set_title("Lines (red), corners (green)")

for a in ax:
  a.axis("off")

plt.tight_layout()
plt.show()

print("Detected line segments:", line_count)
print("Detected corners:", corner_count)

